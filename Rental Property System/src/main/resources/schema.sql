CREATE TABLE USERS (
    USER_ID             NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME            VARCHAR2(50)    NOT NULL UNIQUE,
    PASSWORD_HASH       VARCHAR2(255)   NOT NULL,
    USER_TYPE           CHAR(1)         CHECK (USER_TYPE IN ('0', '1')) NOT NULL
);

CREATE TABLE PROPERTIES (
    PROPERTY_ID         NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUILDING_NAME       VARCHAR2(150),
    ADDRESS             VARCHAR2(255)   NOT NULL, 
    UNIT_NUMBER         VARCHAR2(20),  
    PRICE               NUMBER(10, 2)   NOT NULL,
    NUM_BEDROOMS        NUMBER(2),
    SQUARE_METERS       NUMBER(8, 2),
    DESCRIPTION         VARCHAR2(4000), 
    LISTING_USER_ID     NUMBER          NOT NULL,
    GEOMETRY            SDO_GEOMETRY,
    FOREIGN KEY (LISTING_USER_ID) REFERENCES USERS(USER_ID)
);

CREATE TABLE PROPERTY_IMAGES (
    IMAGE_ID            NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROPERTY_ID         NUMBER          NOT NULL,
    IMAGE_NAME          VARCHAR2(100),
    UPLOAD_DATE         DATE            DEFAULT SYSDATE,

    IMAGE_DATA          ORDSYS.ORDImage,
    IMAGE_SI            ORDSYS.SI_StillImage,
   
    IMAGE_AC            ORDSYS.SI_AverageColor,
    IMAGE_CH            ORDSYS.SI_ColorHistogram,
    IMAGE_PC            ORDSYS.SI_PositionalColor,
    IMAGE_TX            ORDSYS.SI_Texture,
    FOREIGN KEY (PROPERTY_ID) REFERENCES PROPERTIES(PROPERTY_ID) ON DELETE CASCADE
);

--Trigger for image features generation. see: https://rychly-edu.gitlab.io/dbs/multimedia/oracle/#storing-images
CREATE OR REPLACE TRIGGER images_generateFeatures
 BEFORE INSERT OR UPDATE OF IMAGE_DATA ON PROPERTY_IMAGES
 FOR EACH ROW
DECLARE
 si ORDSYS.SI_StillImage;
BEGIN
 -- if there is any photo (it is not an empty image) then generate its features
 IF :NEW.IMAGE_DATA.height IS NOT NULL THEN
    si := new SI_StillImage(:NEW.IMAGE_DATA.getContent());
    :NEW.IMAGE_SI := si;
    :NEW.IMAGE_AC := SI_AverageColor(si);
    :NEW.IMAGE_CH := SI_ColorHistogram(si);
    :NEW.IMAGE_PC := SI_PositionalColor(si);
    :NEW.IMAGE_TX := SI_Texture(si);
 END IF;
END;
/

