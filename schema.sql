--users table : it holds the users of the software. hashing the password is the job of the java software

CREATE TABLE USERS (
    USER_ID             NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME            VARCHAR2(50)    NOT NULL UNIQUE,
    PASSWORD_HASH       VARCHAR2(255)   NOT NULL,
    EMAIL               VARCHAR2(100)   NOT NULL UNIQUE,
    FIRST_NAME          VARCHAR2(50),
    LAST_NAME           VARCHAR2(50),
    REGISTRATION_DATE   DATE            DEFAULT SYSDATE
);


--building table. by the way a building can have many rental units

CREATE TABLE BUILDINGS (
    BUILDING_ID         NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUILDING_NAME       VARCHAR2(150),
    ADDRESS             VARCHAR2(255)   NOT NULL UNIQUE,
    GEOMETRY            MDSYS.SDO_GEOMETRY NOT NULL
);

-- any rentable unit, linked to a Building. building and property are the same example:  say a bungalow.

CREATE TABLE PROPERTIES (
    PROPERTY_ID         NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UNIT_NUMBER         VARCHAR2(20),   -- house number that is optional
    PRICE               NUMBER(10, 2)   NOT NULL,
    NUM_BEDROOMS        NUMBER(2),
    SQUARE_METERS       NUMBER(8, 2),
    DESCRIPTION         CLOB,
    BUILDING_ID         NUMBER          NOT NULL,
    LISTING_USER_ID     NUMBER          NOT NULL,
    UNIT_GEOMETRY       MDSYS.SDO_GEOMETRY, -- Point for an apartment, Polygon for a house

    --some relations == unit belongs to both buildings and users
    FOREIGN KEY (BUILDING_ID) REFERENCES BUILDINGS(BUILDING_ID),
    FOREIGN KEY (LISTING_USER_ID) REFERENCES USERS(USER_ID)
);

-- photograph of houses to implement multimedia requirements

CREATE TABLE PROPERTY_IMAGES (
    IMAGE_ID            NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROPERTY_ID         NUMBER          NOT NULL,
    IMAGE_NAME          VARCHAR2(100),
    UPLOAD_DATE         DATE            DEFAULT SYSDATE,
    IMAGE_DATA          ORDSYS.ORDImage,
    FOREIGN KEY (PROPERTY_ID) REFERENCES PROPERTIES(PROPERTY_ID) ON DELETE CASCADE --deleting property delets all images related to it
);




-- other Spatial  Tables we need. they are unrelated to rentals. we may need to add some user role who can CRUD them.

CREATE TABLE NEIGHBORHOOD_ZONES (
    ZONE_ID             NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME                VARCHAR2(100)   NOT NULL UNIQUE,
    GEOMETRY            MDSYS.SDO_GEOMETRY
);

CREATE TABLE SCHOOL_CATCHMENT_AREAS (
    AREA_ID             NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME                VARCHAR2(100)   NOT NULL UNIQUE,
    GEOMETRY            MDSYS.SDO_GEOMETRY
);

CREATE TABLE TRANSIT_STOPS (
    STOP_ID             NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME                VARCHAR2(100)   NOT NULL,
    GEOMETRY            MDSYS.SDO_GEOMETRY
);

CREATE TABLE CELLULAR_COVERAGE (
    COVERAGE_ID         NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVIDER_NAME       VARCHAR2(100)   NOT NULL,
    GEOMETRY            MDSYS.SDO_GEOMETRY
);


